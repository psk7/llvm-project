#ifndef LLVM_PDP_SUBTARGET_H
#define LLVM_PDP_SUBTARGET_H

#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#include "PDPFrameLowering.h"
#include "PDPISelLowering.h"
#include "PDPInstrInfo.h"
#include "PDPSelectionDAGInfo.h"
#include "MCTargetDesc/PDPMCTargetDesc.h"

#define GET_SUBTARGETINFO_HEADER
#include "PDPGenSubtargetInfo.inc"

namespace llvm {

/// A specific PDP target MCU.
class PDPSubtarget : public PDPGenSubtargetInfo {
public:
  //! Creates an PDP subtarget.
  //! \param TT  The target triple.
  //! \param CPU The CPU to target.
  //! \param FS  The feature string.
  //! \param TM  The target machine.
  PDPSubtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
               const PDPTargetMachine &TM);

  const PDPInstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const PDPTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const PDPSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  const PDPRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  /// Parses a subtarget feature string, setting appropriate options.
  /// \note Definition of function is auto generated by `tblgen`.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  PDPSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS,
                                                const TargetMachine &TM);

  // Subtarget feature getters.
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool GETTER() const { return ATTRIBUTE; }
#include "PDPGenSubtargetInfo.inc"

  bool enableSubRegLiveness() const override { return true; }

  /// Gets the ELF architecture for the e_flags field
  /// of an ELF object file.
  unsigned getELFArch() const {
    assert(ELFArch != 0 &&
           "every device must have an associate ELF architecture");
    return ELFArch;
  }

private:
  /// The ELF e_flags architecture.
  unsigned ELFArch = 0;

  // Subtarget feature settings
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool ATTRIBUTE = DEFAULT;
#include "PDPGenSubtargetInfo.inc"

  PDPInstrInfo InstrInfo;
  PDPFrameLowering FrameLowering;
  PDPTargetLowering TLInfo;
  PDPSelectionDAGInfo TSInfo;
};

} // end namespace llvm

#endif // LLVM_PDP_SUBTARGET_H
