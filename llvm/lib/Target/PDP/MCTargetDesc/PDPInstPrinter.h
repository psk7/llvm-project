#ifndef LLVM_PDP_INST_PRINTER_H
#define LLVM_PDP_INST_PRINTER_H

#include "llvm/MC/MCInstPrinter.h"

#include "MCTargetDesc/PDPMCTargetDesc.h"

namespace llvm {

/// Prints PDP instructions to a textual stream.
class PDPInstPrinter : public MCInstPrinter {
public:
  PDPInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {
    PrintImmOct = true;
  }

  static const char *getPrettyRegisterName(MCRegister Reg,
                                           MCRegisterInfo const &MRI);

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

private:
  static const char *getRegisterName(MCRegister Reg,
                                     unsigned AltIdx = PDP::NoRegAltName);

  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printPCRelImm(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printPCRelImm(const MCInst *MI, uint64_t /*Address*/, unsigned OpNo,
                     raw_ostream &O) {
    printPCRelImm(MI, OpNo, O);
  }

  void printUniop(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBrcond(const MCInst *MI, unsigned OpNo, raw_ostream &O);

  // Autogenerated by TableGen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &O);
  void printCustomAliasOperand(const MCInst *MI, uint64_t Address,
                               unsigned OpIdx, unsigned PrintMethodIdx,
                               raw_ostream &O);
};

} // end namespace llvm

#endif // LLVM_PDP_INST_PRINTER_H
