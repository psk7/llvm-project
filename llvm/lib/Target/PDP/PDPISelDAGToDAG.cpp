bool PDPDAGToDAGISel::SelectUniTgt(SDValue N, SDValue &Base, SDValue &Mode, SDValue &Disp, SDValue &Offs) const {
  const SDLoc Dl(N);
  auto DL = CurDAG->getDataLayout();

  if (const StoreSDNode *S = dyn_cast<StoreSDNode>(N)) {
    return SelectUniPtrStore(S, Base, Mode, Disp, Offs);
  }

  return false;
}

bool PDPDAGToDAGISel::SelectUniRMW(SDValue N, SDValue &Base, SDValue &Mode, SDValue &Disp, SDValue &Offs) const {
  const SDLoc Dl(N);
  auto DL = CurDAG->getDataLayout();

  if (const auto *L = dyn_cast<LoadSDNode>(N)) {
    if (isNullConstantOrUndef(L->getOffset())) {
      return SelectReference(L->getBasePtr(), Base, Mode, Disp, Offs, 7);
    }
  }

  return SelectReference(N, Base, Mode, Disp, Offs, 6);
}

