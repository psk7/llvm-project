bool PDPDAGToDAGISel::SelectUniMem(SDNode *Op, SDValue N, SDValue &Base,
                                   SDValue &Mode, SDValue &Disp) {
  SDLoc Dl(N);

  N.dumpr(CurDAG);

  if (N.getOpcode() == PDPISD::WRAPPER ||
      N.getOpcode() == ISD::TargetGlobalAddress) {
    Base = CurDAG->getRegister(PDP::R7, MVT::i16);
    Mode = CurDAG->getTargetConstant(3, Dl, MVT::i16);
    Disp = N;

    return true;
  }

  if (const MemSDNode *M = dyn_cast<MemSDNode>(N)) {
    auto &Op = M->getOperand(1);

    Op.dumpr(CurDAG);

    if (Op.getOpcode() == PDPISD::WRAPPER) {
      Base = CurDAG->getRegister(PDP::R7, MVT::i16);
      Mode = CurDAG->getTargetConstant(3, Dl, MVT::i16);
      Disp = Op.getOperand(0);

      Base.dumpr(CurDAG);
      Mode.dumpr(CurDAG);
      Disp.dumpr(CurDAG);

      return true;
    }

    if (Op.getOpcode() == ISD::TargetGlobalAddress) {
      Base = CurDAG->getRegister(PDP::R7, MVT::i16);
      Mode = CurDAG->getTargetConstant(3, Dl, MVT::i16);
      Disp = Op;

      return true;
    }
  }

  return false;
}

bool PDPDAGToDAGISel::SelectAddr(SDNode *Op, SDValue N, SDValue &Base,
                                 SDValue &Disp) {
  SDLoc dl(Op);
  auto DL = CurDAG->getDataLayout();
  MVT PtrVT = getTargetLowering()->getPointerTy(DL);

  // if the address is a frame index get the TargetFrameIndex.
  if (const FrameIndexSDNode *FIN = dyn_cast<FrameIndexSDNode>(N)) {
    Base = CurDAG->getTargetFrameIndex(FIN->getIndex(), PtrVT);
    Disp = CurDAG->getTargetConstant(0, dl, MVT::i8);

    return true;
  }

  // Match simple Reg + uimm6 operands.
  if (N.getOpcode() != ISD::ADD && N.getOpcode() != ISD::SUB &&
      !CurDAG->isBaseWithConstantOffset(N)) {
    return false;
  }

  if (const ConstantSDNode *RHS = dyn_cast<ConstantSDNode>(N.getOperand(1))) {
    int RHSC = (int)RHS->getZExtValue();

    // Convert negative offsets into positives ones.
    if (N.getOpcode() == ISD::SUB) {
      RHSC = -RHSC;
    }

    // <#Frame index + const>
    // Allow folding offsets bigger than 63 so the frame pointer can be used
    // directly instead of copying it around by adjusting and restoring it for
    // each access.
    if (N.getOperand(0).getOpcode() == ISD::FrameIndex) {
      int FI = cast<FrameIndexSDNode>(N.getOperand(0))->getIndex();

      Base = CurDAG->getTargetFrameIndex(FI, PtrVT);
      Disp = CurDAG->getTargetConstant(RHSC, dl, MVT::i16);

      return true;
    }

    // The value type of the memory instruction determines what is the maximum
    // offset allowed.
    MVT VT = cast<MemSDNode>(Op)->getMemoryVT().getSimpleVT();

    // We only accept offsets that fit in 6 bits (unsigned), with the
    // exception of 16-bit loads - those can only go up to 62, because we
    // desugar them into a pair of 8-bit loads like `ldd rx, RHSC` + `ldd ry,
    // RHSC + 1`.
    bool OkI8 = VT == MVT::i8 && RHSC <= 63;
    bool OkI16 = VT == MVT::i16 && RHSC <= 62;

    if (OkI8 || OkI16) {
      Base = N.getOperand(0);
      Disp = CurDAG->getTargetConstant(RHSC, dl, MVT::i8);

      return true;
    }
  }

  return false;
}

void PDPDAGToDAGISel::SelectReference(const SDValue &N, SDValue &Base, SDValue &Mode, SDValue &Disp,
                                      const int OpMode) const {
  const SDLoc Dl(N);
  const auto DL = CurDAG->getDataLayout();

  const MVT PtrVT = getTargetLowering()->getPointerTy(DL);

  if (const FrameIndexSDNode *FIN = dyn_cast<FrameIndexSDNode>(N)) {
    Base = CurDAG->getRegister(PDP::R6, MVT::i16);
    Mode = CurDAG->getTargetConstant(OpMode, Dl, MVT::i16);
    Disp = CurDAG->getTargetFrameIndex(FIN->getIndex(), PtrVT);
    return;
  }

  if (N.getOpcode() == ISD::CopyFromReg) {
    if (const RegisterSDNode *R = dyn_cast<RegisterSDNode>(N.getOperand(1))) {
      Base = CurDAG->getRegister(R->getReg(), MVT::i16);
      Mode = CurDAG->getTargetConstant(OpMode, Dl, MVT::i16);
      Disp = CurDAG->getTargetConstant(0, Dl, PtrVT);
      return;
    }
  }

  if (N.getOpcode() == ISD::Register) {
    if (const RegisterSDNode *R = dyn_cast<RegisterSDNode>(N)) {
      Base = CurDAG->getRegister(R->getReg(), MVT::i16);
      Mode = CurDAG->getTargetConstant(OpMode, Dl, MVT::i16);
      Disp = CurDAG->getTargetConstant(0, Dl, PtrVT);
      return;
    }
  }

  if (N.getOpcode() == PDPISD::WRAPPER && OpMode == 6) {
    if (isa<GlobalAddressSDNode>(N.getOperand(0))) {
      Base = CurDAG->getRegister(PDP::R7, MVT::i16);
      Mode = CurDAG->getTargetConstant(3, Dl, MVT::i16);
      Disp = N.getOperand(0);
    }
    return;
  }

  if (const RegisterSDNode *R = dyn_cast<RegisterSDNode>(N.getOperand(0))) {
    Base = CurDAG->getRegister(R->getReg(), MVT::i16);
    Mode = CurDAG->getTargetConstant(OpMode, Dl, MVT::i16);
    Disp = CurDAG->getTargetConstant(0, Dl, PtrVT);
    return;
  }

  Base = N;
  Mode = CurDAG->getTargetConstant(OpMode, Dl, MVT::i16);
  Disp = CurDAG->getTargetConstant(0, Dl, PtrVT);
}

bool PDPDAGToDAGISel::SelectReference(const SDValue &N, SDValue &Base,
                                      SDValue &Mode, SDValue &Disp,
                                      SDValue &Offs, int OpMode) const {

  const SDLoc Dl(N);
  const auto DL = CurDAG->getDataLayout();

  const ConstantSDNode *C = dyn_cast<ConstantSDNode>(N);
  if (C && OpMode == 6) {
    Base = CurDAG->getRegister(PDP::R7, MVT::i16);
    Mode = CurDAG->getTargetConstant(3, Dl, MVT::i16);
    Disp = CurDAG->getTargetConstant(C->getAPIntValue(), Dl, MVT::i16);
    Offs = CurDAG->getTargetConstant(0, Dl, MVT::i16);
    return true;
  }

  if (C && OpMode == 7)
    return false;

  if (N->getOpcode() == ISD::ADD) {
    const ConstantSDNode *C0 = dyn_cast<ConstantSDNode>(N.getOperand(0));
    const ConstantSDNode *C1 = dyn_cast<ConstantSDNode>(N.getOperand(1));

    if (C0 != nullptr) {
        SelectReference(N.getOperand(1), Base, Mode, Disp, OpMode);
        Offs = CurDAG->getTargetConstant(C0->getAPIntValue(), Dl, MVT::i16);
        return true;
    }

    if (C1 != nullptr) {
        SelectReference(N->getOperand(0), Base, Mode, Disp, OpMode);
        Offs = CurDAG->getTargetConstant(C1->getAPIntValue(), Dl, MVT::i16);
        return true;
    }
  }

  SelectReference(SDValue(N), Base, Mode, Disp, OpMode);
  Offs = CurDAG->getTargetConstant(0, Dl, MVT::i16);

  return true;
}

bool PDPDAGToDAGISel::SelectUniPtrLoad(const LoadSDNode *L, const SDValue &LV,
                                       SDValue &Base, SDValue &Mode,
                                       SDValue &Disp, SDValue &Offs,
                                       bool CheckUsers) const {
  if (L->use_size() > 1 && CheckUsers) {
    Base = LV;
    Mode = CurDAG->getTargetConstant(0, SDLoc(), MVT::i16);
    Disp = CurDAG->getTargetConstant(0, SDLoc(), MVT::i16);
    Offs = CurDAG->getTargetConstant(0, SDLoc(), MVT::i16);
    return true;
  }

  if (isNullConstantOrUndef(L->getOffset())) {
    if (const LoadSDNode *LS = dyn_cast<LoadSDNode>(L->getBasePtr())) {
      // Косвенная индексная адресация
      return SelectReference(LS->getBasePtr(), Base, Mode, Disp, Offs, 7);
    }
  }

  return SelectReference(L->getBasePtr(), Base, Mode, Disp, Offs, 6);
}

bool PDPDAGToDAGISel::SelectNotImm(const SDValue &N, SDValue &Base) const {
  auto r = isa<ConstantSDNode>(N);

  if (!r) {
    Base = N;
  }

  return !r;
}

bool PDPDAGToDAGISel::SelectUniPtrStore(const StoreSDNode *S, SDValue &Base,
                                        SDValue &Mode, SDValue &Disp,
                                        SDValue &Offs) const {
  SDLoc Dl(S);
  auto DL = CurDAG->getDataLayout();

  if (isNullConstantOrUndef(S->getOffset())) {
    if (const LoadSDNode *LS = dyn_cast<LoadSDNode>(S->getBasePtr())) {
      // Косвенная индексная адресация
      return SelectReference(LS->getBasePtr(), Base, Mode, Disp, Offs, 7);
    }
  }

  return SelectReference(S->getBasePtr(), Base, Mode, Disp, Offs, 6);
}

bool PDPDAGToDAGISel::SelectUniLoad(SDNode *Op, SDValue N, SDValue &Base,
                                   SDValue &Mode, SDValue &Disp, SDValue &Offs) const {

  if (const LoadSDNode *L = dyn_cast<LoadSDNode>(Op)) {
    return SelectUniPtrLoad(L, SDValue(Op, 0), Base, Mode, Disp, Offs);
  }

  return false;
}

bool PDPDAGToDAGISel::SelectUniStore(SDNode *Op, SDValue N, SDValue &Base,
                                   SDValue &Mode, SDValue &Disp, SDValue &Offs) const {
  if (const StoreSDNode *S = dyn_cast<StoreSDNode>(Op)) {
    return SelectUniPtrStore(S, Base, Mode, Disp, Offs);
  }

  return false;
}

